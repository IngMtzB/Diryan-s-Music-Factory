/**
 * Resolve complete parametric configuration for any waveform preset or custom override.
 */
export function resolveWaveformPreset(styleId, customParams = null, catalogPresets = null) {
  const list =
    Array.isArray(catalogPresets) && catalogPresets.length > 0
      ? catalogPresets
      : DEFAULT_WAVEFORM_PRESETS;

  let found = list.find((p) => p.id === styleId);
  if (!found) {
    found = DEFAULT_WAVEFORM_PRESETS.find((p) => p.id === styleId) || DEFAULT_WAVEFORM_PRESETS[0];
  }

  const defaultBase =
    DEFAULT_WAVEFORM_PRESETS.find((p) => p.id === found.engine) || DEFAULT_WAVEFORM_PRESETS[0];

  const mergedParams = {
    ...defaultBase.params,
    ...(found.params || {}),
    ...(customParams || {}),
    engine: customParams?.engine || found.engine || found.params?.engine || 'rounded_mirror',
  };

  return {
    ...found,
    engine: mergedParams.engine,
    params: mergedParams,
  };
}

